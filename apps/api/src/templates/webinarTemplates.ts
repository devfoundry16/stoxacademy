/** "باقي {left}" with correct Arabic counting: يوم واحد / يومان / 3–10 أيام / 11+ يومًا. */
export function arabicDaysLeft(n: number): string {
    if (n === 1) return "يوم واحد";
    if (n === 2) return "يومان";
    if (n <= 10) return `${n} أيام`;
    return `${n} يومًا`;
}

const TOKENS = ["name", "left", "date", "time", "link", "support"] as const;
type TokenValues = Partial<Record<(typeof TOKENS)[number], string>>;

const fill = (text: string, v: TokenValues) => text.replace(/\{(\w+)\}/g, (m, k) => (v as any)[k] ?? m);

const escapeHtml = (s: string) =>
    s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]!));

const ARABIC_MONTHS = ["يناير", "فبراير", "مارس", "أبريل", "مايو", "يونيو", "يوليو", "أغسطس", "سبتمبر", "أكتوبر", "نوفمبر", "ديسمبر"];

/** "2 ديسمبر 2026" and "5:00 مساءً بتوقيت القدس" for the webinar's start time. */
export function webinarLabels(startsAt: Date): { date: string; time: string } {
    const p = jerusalemParts(startsAt);
    const hour12 = p.hour % 12 || 12;
    return {
        date: `${p.day} ${ARABIC_MONTHS[p.month - 1]} ${p.year}`,
        time: `${hour12}:${String(p.minute).padStart(2, "0")} ${p.hour < 12 ? "صباحًا" : "مساءً"} بتوقيت القدس`,
    };
}

function baseValues(name: string, webinar: Webinar): TokenValues {
    return { name, ...webinarLabels(webinar.startsAt), link: webinarLink(webinar.id), support: SUPPORT_NUMBER };
}

/** Renders a webinar email. key: "confirmation" | "countdown_<1-14>" | "reminder_1h". */
export function renderWebinarEmail(key: string, fullName: string, webinar: Webinar): { subject: string; html: string } {
    let email: WebinarEmail | undefined;
    const values = baseValues(escapeHtml(fullName), webinar);
    if (key === "confirmation") email = CONFIRMATION_EMAIL;
    else if (key === "reminder_1h") email = ONE_HOUR_EMAIL;
    else if (key.startsWith("countdown_")) {
        const n = Number(key.slice("countdown_".length));
        email = COUNTDOWN_EMAILS[n - 1];
        values.left = arabicDaysLeft(14 - n);
    }
    if (!email) throw new Error(`Unknown webinar email: ${key}`);

    const body = email.lines
        .map((line) =>
            line === "{link}"
                ? `<p dir="ltr" style="margin:0 0 12px;text-align:right;word-break:break-all;"><a href="${values.link}" style="color:#667eea;">${values.link}</a></p>`
                : `<p dir="rtl" style="margin:0 0 12px;text-align:right;">${fill(line, { ...values, support: `<span dir="ltr">${SUPPORT_NUMBER}</span>` })}</p>`
        )
        .join("\n");

    const html = `<!DOCTYPE html>
<html lang="ar" dir="rtl">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1.0"><title>${email.subject}</title></head>
<body dir="rtl" style="font-family: Tahoma, Arial, sans-serif; line-height: 1.8; color: #333; max-width: 600px; margin: 0 auto; padding: 20px; text-align: right;">
<div dir="rtl" style="direction: rtl; text-align: right; font-family: Tahoma, Arial, sans-serif; line-height: 1.8; color: #333; max-width: 600px; margin: 0 auto; background: #f9f9f9; padding: 30px; border-radius: 10px;">
${body}
</div>
</body>
</html>`;

    return { subject: fill(email.subject, values), html };
}

/** Token names in order of first appearance, i.e. the order of {{1}}, {{2}}, ... in the approved Meta template. */
export function whatsappParamOrder(body: string): string[] {
    return [...new Set([...body.matchAll(/\{(\w+)\}/g)].map((m) => m[1]))];
}

export function whatsappParams(key: string, fullName: string, webinar: Webinar): { name: string; params: string[] } {
    const t = WHATSAPP_TEMPLATES[key];
    if (!t) throw new Error(`Unknown WhatsApp template: ${key}`);
    const values = baseValues(fullName, webinar) as Record<string, string>;
    return { name: t.name, params: whatsappParamOrder(t.body).map((k) => values[k]) };
}
