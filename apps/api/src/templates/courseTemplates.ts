const SUPPORT = `‎${SUPPORT_NUMBER}‎`; // LRM marks keep "+" before the digits in Arabic text

/** Session number a reminder key belongs to ("s3_morning" → 3), or null for the confirmation. */
export function reminderSession(key: string): number | null {
    const m = key.match(/^s(\d+)_(morning|1h)$/);
    return m ? Number(m[1]) : null;
}

/** key: "confirmation" | "s<1-8>_morning" | "s<1-8>_1h". */
export function renderCourseEmail(key: string, fullName: string): { subject: string; html: string } {
    const values = { name: escapeHtml(fullName), support: SUPPORT };
    if (key === "confirmation") return renderArabicEmail(COURSE_CONFIRMATION_EMAIL, values);
    const pair = SESSION_REMINDER_EMAILS[(reminderSession(key) ?? 0) - 1];
    if (!pair) throw new Error(`Unknown course email: ${key}`);
    return renderArabicEmail(key.endsWith("_morning") ? pair.morning : pair.oneHour, values);
}
